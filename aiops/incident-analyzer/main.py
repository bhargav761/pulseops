# --------------------------------------------------
# Prometheus
# --------------------------------------------------


async def query_prometheus(query: str) -> Dict[str, Any]:
    """Execute a Prometheus instant query."""
    url = f"{PROMETHEUS_URL}/api/v1/query"

    async with httpx.AsyncClient(timeout=10) as client:
        response = await client.get(url, params={"query": query})
        response.raise_for_status()
        return response.json()


# --------------------------------------------------
# Loki
# --------------------------------------------------


async def query_loki(query: str) -> Dict[str, Any]:
    """Execute a Loki log query."""
    url = f"{LOKI_URL}/loki/api/v1/query"

    async with httpx.AsyncClient(timeout=10) as client:
        response = await client.get(url, params={"query": query})
        response.raise_for_status()
        return response.json()
    
# --------------------------------------------------
# Gemini AI Analysis
# --------------------------------------------------

async def generate_ai_analysis(
    incident: Incident,
    prometheus_data: Dict[str, Any],
    loki_data: Dict[str, Any],
) -> AIResponse:
    """
    Generate AI-powered incident analysis using Gemini.
    """

    prompt = f"""
You are an expert Site Reliability Engineer (SRE) and DevOps Engineer.

Analyze the following production incident.

Service:
{incident.service}

Severity:
{incident.severity}

Incident:
{incident.message}

Prometheus Metrics:
{prometheus_data}

Loki Logs:
{loki_data}

Provide:

1. Executive Summary
2. Most likely Root Cause
3. Final Severity (LOW / MEDIUM / HIGH / CRITICAL)
4. Top 5 Remediation Steps

Respond in plain English.
"""

    try:
        response = gemini_model.generate_content(prompt)

        text = response.text if hasattr(response, "text") else str(response)

        recommendations = []

        for line in text.splitlines():
            line = line.strip()

            if (
                line.startswith("-")
                or line.startswith("*")
                or line[:2].isdigit()
            ):
                recommendations.append(line.lstrip("-*0123456789. ").strip())

        if not recommendations:
            recommendations = [
                "Inspect Kubernetes events.",
                "Review Prometheus metrics.",
                "Check Loki logs.",
                "Verify latest deployment.",
                "Restart unhealthy pods if required.",
            ]

        return AIResponse(
            summary=text,
            root_cause="Generated by Gemini AI",
            severity=incident.severity.upper(),
            recommendations=recommendations[:5],
        )

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Gemini analysis failed: {exc}",
        )


# --------------------------------------------------
# Collect Monitoring Data
# --------------------------------------------------

async def collect_monitoring_data() -> Dict[str, Any]:
    """
    Collect key metrics from Prometheus and Loki.
    """

    metrics = {}

    try:
        metrics["cpu"] = await query_prometheus(
            '100 - (avg by(instance)(rate(node_cpu_seconds_total{mode="idle"}[5m])) * 100)'
        )

        metrics["memory"] = await query_prometheus(
            '(1 - (node_memory_MemAvailable_bytes / node_memory_MemTotal_bytes)) * 100'
        )

        metrics["pods"] = await query_prometheus(
            'up'
        )

    except Exception as exc:
        metrics["prometheus_error"] = str(exc)

    try:
        metrics["logs"] = await query_loki('{job="varlogs"}')

    except Exception as exc:
        metrics["loki_error"] = str(exc)

    return metrics


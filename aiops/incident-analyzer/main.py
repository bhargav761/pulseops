@app.get("/metrics")
async def metrics():
    """
    Return current monitoring data from Prometheus and Loki.
    """
    return await collect_monitoring_data()


@app.post("/analyze", response_model=AIResponse)
async def analyze_incident(incident: Incident):
    """
    Perform AI-powered incident analysis.
    """
    monitoring_data = await collect_monitoring_data()

    prometheus_data = {
        k: v for k, v in monitoring_data.items() if k != "logs"
    }

    loki_data = monitoring_data.get("logs", {})

    return await generate_ai_analysis(
        incident,
        prometheus_data,
        loki_data,
    )


